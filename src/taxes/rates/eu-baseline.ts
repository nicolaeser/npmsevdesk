export function normalizeCountryCode(countryCode: string): string {
  if (typeof countryCode !== "string") {
    throw new SevdeskConfigurationError("countryCode must be an ISO 3166-1 alpha-2 string.");
  }
  const upper = countryCode.trim().toUpperCase();
  return upper === "EL" ? "GR" : upper;
}

export function isIsoCountryCode(countryCode: string): boolean {
  return ISO_3166_ALPHA_2.has(normalizeCountryCode(countryCode));
}

export function isEuMemberCountry(countryCode: string): boolean {
  const code = normalizeCountryCode(countryCode);
  return code === "DE" || Object.hasOwn(EU_STANDARD_VAT_RATES, code);
}
